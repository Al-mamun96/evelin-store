import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const dir=mkdtempSync(join(tmpdir(),'evelin-customers-'));
process.env.DATABASE_PATH=join(dir,'store.sqlite');
const {db}=await import('../lib/db.ts');
const {registerCustomer,loginCustomer,sessionCustomer,endSession,updateCustomer,changeCustomerPassword}=await import('../lib/customers.ts');
test('customer isolation, password hashing, session rotation and expiry',async()=>{
 const password='Synthetic secure phrase 123';
 const a=await registerCustomer({name:'Customer Alpha',email:'ALPHA@example.test',password});
 const b=await registerCustomer({name:'Customer Beta',email:'beta@example.test',password});
 assert.equal(a.customer.email,'alpha@example.test');
 assert.equal(sessionCustomer(a.token)?.id,a.customer.id);
 assert.equal(sessionCustomer('bad-token'),null);
 const stored=db().prepare('SELECT password_hash FROM customers WHERE id=?').get(a.customer.id)!;
 assert.ok(String(stored.password_hash).startsWith('scrypt$'));
 assert.ok(!String(stored.password_hash).includes(password));
 assert.equal(db().prepare('SELECT token_hash FROM customer_sessions WHERE token_hash=?').get(a.token),undefined);
 await assert.rejects(()=>registerCustomer({name:'Duplicate',email:'alpha@example.test',password}));
 await assert.rejects(()=>loginCustomer({email:'alpha@example.test',password:'wrong'}));
 await assert.rejects(()=>loginCustomer({email:'missing@example.test',password}));
 const changed=updateCustomer(a.token,{id:b.customer.id,name:'Alpha Updated',phone:'+8801700000000',address:'Synthetic address'});
 assert.equal(changed.id,a.customer.id);assert.equal(changed.phone,'01700000000');
 assert.equal(sessionCustomer(b.token)?.name,'Customer Beta');
 assert.throws(()=>updateCustomer(undefined,{name:'Unauthenticated'}));
 const second=await loginCustomer({email:'alpha@example.test',password});
 await assert.rejects(()=>changeCustomerPassword(a.token,{currentPassword:'wrong',newPassword:'New synthetic phrase 456'}));
 const rotated=await changeCustomerPassword(a.token,{currentPassword:password,newPassword:'New synthetic phrase 456'});
 assert.equal(sessionCustomer(a.token),null);assert.equal(sessionCustomer(second.token),null);
 assert.equal(sessionCustomer(rotated.token)?.name,'Alpha Updated');
 await assert.rejects(()=>loginCustomer({email:'alpha@example.test',password}));
 const fresh=await loginCustomer({email:'alpha@example.test',password:'New synthetic phrase 456'});
 endSession(fresh.token);assert.equal(sessionCustomer(fresh.token),null);
 db().prepare('UPDATE customer_sessions SET last_seen=0 WHERE customer_id=?').run(b.customer.id);
 assert.equal(sessionCustomer(b.token),null);
 db().prepare('UPDATE customer_sessions SET expires=0 WHERE customer_id=?').run(a.customer.id);
 assert.equal(sessionCustomer(rotated.token),null);
});
after(()=>{db().close();rmSync(dir,{recursive:true,force:true});});
